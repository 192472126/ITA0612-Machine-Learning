import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_classification
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

class LogisticRegressionFromScratch:
    def __init__(self, learning_rate=0.01, num_iterations=1000):
        self.learning_rate = learning_rate
        self.num_iterations = num_iterations
        self.weights = None
        self.bias = None

    def _sigmoid(self, z):
        # Stable sigmoid function to avoid overflow
        return 1 / (1 + np.exp(-np.clip(z, -500, 500)))

    def fit(self, X, y):
        num_samples, num_features = X.shape
        # Initialize parameters
        self.weights = np.zeros(num_features)
        self.bias = 0.0

        # Gradient Descent
        for _ in range(self.num_iterations):
            # Approximate y with linear combination of weights and x, plus bias
            linear_model = np.dot(X, self.weights) + self.bias
            # Apply sigmoid activation function
            y_predicted = self._sigmoid(linear_model)

            # Compute gradients
            dw = (1 / num_samples) * np.dot(X.T, (y_predicted - y))
            db = (1 / num_samples) * np.sum(y_predicted - y)

            # Update parameters
            self.weights -= self.learning_rate * dw
            self.bias -= self.learning_rate * db

    def predict_proba(self, X):
        linear_model = np.dot(X, self.weights) + self.bias
        return self._sigmoid(linear_model)

    def predict(self, X, threshold=0.5):
        y_predicted_cls = [1 if i > threshold else 0 for i in self.predict_proba(X)]
        return np.array(y_predicted_cls)

# 1. Generate a synthetic dataset
X, y = make_classification(n_samples=1000, n_features=2, n_redundant=0, n_informative=2,
                           random_state=42, n_clusters_per_class=1)

# 2. Split into train and test sets
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=1234)

# 3. Standardize features for better convergence
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# 4. Instantiate and Train the model
model = LogisticRegressionFromScratch(learning_rate=0.1, num_iterations=1000)
model.fit(X_train, y_train)

# 5. Make predictions and evaluate accuracy
predictions = model.predict(X_test)
accuracy = np.mean(predictions == y_test) * 100
print(f"Classification Accuracy: {accuracy:.2f}%")

# 6. Visualize the Decision Boundary
plt.figure(figsize=(8, 6))
# Plot training data
plt.scatter(X_train[:, 0], X_train[:, 1], c=y_train, cmap='bwr', alpha=0.6, edgecolors='k', label='Train Data')

# Plot the decision boundary line: w0*x0 + w1*x1 + b = 0  =>  x1 = -(w0*x0 + b) / w1
x0_boundary = np.linspace(X_train[:, 0].min(), X_train[:, 0].max(), 100)
x1_boundary = -(model.weights[0] * x0_boundary + model.bias) / model.weights[1]
plt.plot(x0_boundary, x1_boundary, color='black', linewidth=2, label='Decision Boundary')

plt.title('Logistic Regression Decision Boundary')
plt.xlabel('Feature 1 (Standardized)')
plt.ylabel('Feature 2 (Standardized)')
plt.legend()
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()