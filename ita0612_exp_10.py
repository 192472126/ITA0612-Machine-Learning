import numpy as np
import matplotlib.pyplot as plt

# 1. Generate Synthetic Data from two 1D Gaussians
np.random.seed(42)
mean1, std1 = 2.0, 1.0
mean2, std2 = 8.0, 1.5

data1 = np.random.normal(mean1, std1, 300)
data2 = np.random.normal(mean2, std2, 700)
X = np.concatenate([data1, data2])

# 2. Initialize Parameters for GMM (2 Components)
# We estimate mean (mu), variance (sigma^2), and mixing weights (pi)
mu = np.array([1.0, 5.0])
var = np.array([1.0, 1.0])
pi = np.array([0.5, 0.5])

n_samples = len(X)
n_components = len(mu)

def normal_pdf(x, mu, var):
    """Calculate probability density function of normal distribution."""
    return (1.0 / np.sqrt(2 * np.pi * var)) * np.exp(-0.5 * ((x - mu) ** 2) / var)

# 3. EM Algorithm Loop
iterations = 50
for i in range(iterations):
    # --- E-Step: Calculate Responsibilities (Posterior probabilities) ---
    responsibilities = np.zeros((n_samples, n_components))
    for k in range(n_components):
        responsibilities[:, k] = pi[k] * normal_pdf(X, mu[k], var[k])

    # Normalize across components
    sum_responsibilities = np.sum(responsibilities, axis=1, keepdims=True)
    responsibilities = responsibilities / sum_responsibilities

    # --- M-Step: Re-estimate parameters using responsibilities ---
    N_k = np.sum(responsibilities, axis=0)

    for k in range(n_components):
        # Update Means
        mu[k] = np.sum(responsibilities[:, k] * X) / N_k[k]
        # Update Variances
        var[k] = np.sum(responsibilities[:, k] * ((X - mu[k]) ** 2)) / N_k[k]
        # Update Weights
        pi[k] = N_k[k] / n_samples

# Print Estimated Parameters
print("=== Estimated Parameters ===")
print(f"Component 1 Mean: {mu[0]:.4f} (True: {mean1})")
print(f"Component 1 Variance: {var[0]:.4f} (True: {std1**2:.4f})")
print(f"Component 2 Mean: {mu[1]:.4f} (True: {mean2})")
print(f"Component 2 Variance: {var[1]:.4f} (True: {std2**2:.4f})")
print(f"Mixing weights: Component 1={pi[0]:.4f}, Component 2={pi[1]:.4f} (True: 0.3, 0.7)")

# Plot the results
x_axis = np.linspace(min(X), max(X), 1000)
y_estimated = pi[0] * normal_pdf(x_axis, mu[0], var[0]) + pi[1] * normal_pdf(x_axis, mu[1], var[1])

plt.figure(figsize=(10, 6))
plt.hist(X, bins=50, density=True, alpha=0.5, color='gray', label='Input Data Histogram')
plt.plot(x_axis, y_estimated, color='red', linewidth=2.5, label='EM Fitted GMM Density')
plt.title('Expectation-Maximization (EM) GMM Fit')
plt.xlabel('Data points')
plt.ylabel('Density')
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.show()