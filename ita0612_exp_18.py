import numpy as np
import matplotlib.pyplot as plt
from sklearn import datasets
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score

# 1. Load the Iris dataset
iris = datasets.load_iris()
X = iris.data[:, [2, 3]]  # Using petal length and petal width for simplicity
y = iris.target

# Since Perceptron is fundamentally a binary classifier,
# let's classify 'Setosa' (0) vs 'Not Setosa' (1 and 2 mapped to 1)
y = np.where(y == 0, 0, 1)

# 2. Split data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42, stratify=y
)

# 3. Standardize features
sc = StandardScaler()
sc.fit(X_train)
X_train_std = sc.transform(X_train)
X_test_std = sc.transform(X_test)

# 4. Implement Perceptron from scratch
class PerceptronClassifier:
    def __init__(self, learning_rate=0.1, n_iterations=50):
        self.lr = learning_rate
        self.n_iter = n_iterations

    def fit(self, X, y):
        # Initialize weights (plus bias weight as the first element)
        self.w_ = np.zeros(1 + X.shape[1])
        self.errors_ = []

        for _ in range(self.n_iter):
            errors = 0
            for xi, target in zip(X, y):
                update = self.lr * (target - self.predict(xi))
                self.w_[1:] += update * xi
                self.w_[0] += update
                errors += int(update != 0.0)
            self.errors_.append(errors)
        return self

    def net_input(self, X):
        return np.dot(X, self.w_[1:]) + self.w_[0]

    def predict(self, X):
        return np.where(self.net_input(X) >= 0.0, 1, 0)

# 5. Train the model
ppn = PerceptronClassifier(learning_rate=0.1, n_iterations=10)
ppn.fit(X_train_std, y_train)

# 6. Predict and evaluate
y_pred = ppn.predict(X_test_std)
print(f"Accuracy: {accuracy_score(y_test, y_pred) * 100:.2f}%")

# 7. Plot decision boundary
def plot_decision_regions(X, y, classifier, resolution=0.02):
    markers = ('s', 'x', 'o', '^', 'v')
    colors = ('red', 'blue', 'lightgreen', 'gray', 'cyan')
    cmap = plt.cm.RdYlBu

    x1_min, x1_max = X[:, 0].min() - 1, X[:, 0].max() + 1
    x2_min, x2_max = X[:, 1].min() - 1, X[:, 1].max() + 1
    xx1, xx2 = np.meshgrid(np.arange(x1_min, x1_max, resolution),
                           np.arange(x2_min, x2_max, resolution))
    Z = classifier.predict(np.array([xx1.ravel(), xx2.ravel()]).T)
    Z = Z.reshape(xx1.shape)
    plt.contourf(xx1, xx2, Z, alpha=0.3, cmap=cmap)
    plt.xlim(xx1.min(), xx1.max())
    plt.ylim(xx2.min(), xx2.max())

    for idx, cl in enumerate(np.unique(y)):
        plt.scatter(x=X[y == cl, 0], y=X[y == cl, 1],
                    alpha=0.8, c=colors[idx],
                    marker=markers[idx], label=f'Class {cl}',
                    edgecolor='black' if markers[idx] == 'o' else 'none')

plt.figure(figsize=(8, 6))
plot_decision_regions(X_train_std, y_train, classifier=ppn)
plt.xlabel('Petal length [standardized]')
plt.ylabel('Petal width [standardized]')
plt.legend(loc='upper left')
plt.title('Perceptron - Iris Classification (Setosa vs Others)')
plt.show()