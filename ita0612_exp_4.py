import numpy as np
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OneHotEncoder, StandardScaler

class NeuralNetwork:
    def __init__(self, input_size, hidden_size, output_size, learning_rate=0.1):
        self.lr = learning_rate
        # Initialize weights with small random values
        self.W1 = np.random.randn(input_size, hidden_size) * 0.01
        self.b1 = np.zeros((1, hidden_size))
        self.W2 = np.random.randn(hidden_size, output_size) * 0.01
        self.b2 = np.zeros((1, output_size))

    def sigmoid(self, x):
        return 1 / (1 + np.exp(-x))

    def sigmoid_derivative(self, x):
        # x is already sigmoid(output)
        return x * (1 - x)

    def forward(self, X):
        # Forward propagation
        self.z1 = np.dot(X, self.W1) + self.b1
        self.a1 = self.sigmoid(self.z1)
        self.z2 = np.dot(self.a1, self.W2) + self.b2
        self.a2 = self.sigmoid(self.z2)
        return self.a2

    def backward(self, X, y, output):
        # Backpropagation of errors
        self.output_error = y - output
        self.output_delta = self.output_error * self.sigmoid_derivative(output)

        self.z1_error = np.dot(self.output_delta, self.W2.T)
        self.z1_delta = self.z1_error * self.sigmoid_derivative(self.a1)

        # Update weights and biases
        self.W1 += np.dot(X.T, self.z1_delta) * self.lr
        self.b1 += np.sum(self.z1_delta, axis=0, keepdims=True) * self.lr
        self.W2 += np.dot(self.a1.T, self.output_delta) * self.lr
        self.b2 += np.sum(self.output_delta, axis=0, keepdims=True) * self.lr

    def train(self, X, y, epochs=1000):
        for epoch in range(epochs):
            output = self.forward(X)
            self.backward(X, y, output)
            if epoch % 100 == 0:
                loss = np.mean(np.square(y - output))
                print(f"Epoch {epoch:4d} - Loss: {loss:.6f}")

# 1. Load and prepare dataset (Iris dataset)
iris = load_iris()
X, y_labels = iris.data, iris.target.reshape(-1, 1)

# Standardize features and One-hot encode targets
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

encoder = OneHotEncoder(sparse_output=False)
y_onehot = encoder.fit_transform(y_labels)

# Split into Train and Test sets
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y_onehot, test_size=0.2, random_state=42
)

# 2. Initialize Neural Network
# Input: 4 features, Hidden: 8 neurons, Output: 3 classes
np.random.seed(42)
nn = NeuralNetwork(input_size=4, hidden_size=8, output_size=3, learning_rate=0.1)

# 3. Train the Network
print("--- Starting Training ---")
nn.train(X_train, y_train, epochs=1000)

# 4. Evaluate the Network
predictions = nn.forward(X_test)
predicted_classes = np.argmax(predictions, axis=1)
true_classes = np.argmax(y_test, axis=1)
accuracy = np.mean(predicted_classes == true_classes) * 100

print("\n--- Evaluation ---")
print(f"Test Accuracy: {accuracy:.2f}%")