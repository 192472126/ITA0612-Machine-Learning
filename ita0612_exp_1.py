def find_s_algorithm(training_data):
    """
    Implements the FIND-S algorithm.

    training_data: A list of tuples, where each tuple is of the form:
                  (attributes_list, target_value)
                  e.g., (['Sunny', 'Warm', 'Normal', 'Strong', 'Warm', 'Same'], 'Yes')
    """
    # Initialize the most specific hypothesis with the first positive training instance
    hypothesis = None

    for attributes, target in training_data:
        if target.lower() == 'yes':
            if hypothesis is None:
                # Initialize with the first positive instance
                hypothesis = list(attributes)
            else:
                # Generalize the hypothesis
                for i in range(len(hypothesis)):
                    if hypothesis[i] != attributes[i]:
                        hypothesis[i] = '?'

    return hypothesis

