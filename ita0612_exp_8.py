import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error, r2_score

# 1. Generate synthetic dataset
np.random.seed(42)
X = 2 * np.random.rand(100, 1)
y = 4 + 3 * X + np.random.randn(100, 1)

# 2. Initialize and fit the Linear Regression model
model = LinearRegression()
model.fit(X, y)

# 3. Predict values
y_pred = model.predict(X)

# 4. Model details and evaluation
print(f"Intercept (theta_0): {model.intercept_[0]:.4f}")
print(f"Slope (theta_1):     {model.coef_[0][0]:.4f}")
print(f"Mean Squared Error:  {mean_squared_error(y, y_pred):.4f}")
print(f"R-squared Score:     {r2_score(y, y_pred):.4f}")

# 5. Plotting results
plt.figure(figsize=(8, 6))
plt.scatter(X, y, color='blue', label='Actual Data')
plt.plot(X, y_pred, color='red', linewidth=2, label='Regression Line')
plt.title('Linear Regression Demonstration')
plt.xlabel('X')
plt.ylabel('y')
plt.legend()
plt.grid(True)
plt.show()