import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
from sklearn.metrics import mean_squared_error, r2_score

# 1. Generate synthetic non-linear data (quadratic relationship)
np.random.seed(42)
X = 2 - 3 * np.random.normal(0, 1, 100)
y = 0.5 * X + 1.5 * (X ** 2) + np.random.normal(-3, 3, 100)

# Reshaping for sklearn
X = X[:, np.newaxis]

# Sort data for smooth plotting
sort_idx = np.argsort(X.flatten())
X_sorted = X[sort_idx]
y_sorted = y[sort_idx]

# 2. Fit Linear Regression model
lin_reg = LinearRegression()
lin_reg.fit(X, y)
y_pred_linear = lin_reg.predict(X_sorted)

# 3. Fit Polynomial Regression model (Degree 2)
poly_features = PolynomialFeatures(degree=2)
X_poly = poly_features.fit_transform(X)

poly_reg = LinearRegression()
poly_reg.fit(X_poly, y)

X_poly_sorted = poly_features.transform(X_sorted)
y_pred_poly = poly_reg.predict(X_poly_sorted)

# 4. Calculate metrics
mse_linear = mean_squared_error(y_sorted, y_pred_linear)
r2_linear = r2_score(y_sorted, y_pred_linear)

mse_poly = mean_squared_error(y_sorted, y_pred_poly)
r2_poly = r2_score(y_sorted, y_pred_poly)

# Print comparison results
print("=== Model Comparison ===")
print(f"Linear Regression     - MSE: {mse_linear:.4f}, R2 Score: {r2_linear:.4f}")
print(f"Polynomial Regression - MSE: {mse_poly:.4f}, R2 Score: {r2_poly:.4f}")

# 5. Plot the results
plt.figure(figsize=(10, 6))
plt.scatter(X, y, color='blue', alpha=0.5, label='Actual Data')
plt.plot(X_sorted, y_pred_linear, color='red', linewidth=2, label='Linear Fit')
plt.plot(X_sorted, y_pred_poly, color='green', linewidth=2, label='Polynomial Fit (Degree 2)')
plt.title('Comparison of Linear and Polynomial Regression')
plt.xlabel('X')
plt.ylabel('y')
plt.legend()
plt.grid(True)
plt.show()