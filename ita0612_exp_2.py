import csv
import pandas as pd

# 1. Create a sample CSV file for demonstration (EnjoySport concept)
data = [
    ['Sunny', 'Warm', 'Normal', 'Strong', 'Warm', 'Same', 'Yes'],
    ['Sunny', 'Warm', 'High', 'Strong', 'Warm', 'Same', 'Yes'],
    ['Rainy', 'Cold', 'High', 'Strong', 'Warm', 'Change', 'No'],
    ['Sunny', 'Warm', 'High', 'Strong', 'Cool', 'Change', 'Yes']
]
columns = ['Sky', 'AirTemp', 'Humidity', 'Wind', 'Water', 'Forecast', 'EnjoySport']

with open('training_data.csv', 'w', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(columns)
    writer.writerows(data)

# 2. Candidate-Elimination Algorithm Implementation
def candidate_elimination(filename):
    # Load dataset
    df = pd.read_csv(filename)
    concepts = df.iloc[:, :-1].values.tolist()
    target = df.iloc[:, -1].values.tolist()

    num_attributes = len(concepts[0])

    # Initialize Specific Boundary (S) and General Boundary (G)
    # S is initialized to the most specific hypothesis (all phi)
    # G is initialized to the most general hypothesis (all ?)
    specific_h = concepts[0].copy() if target[0] == 'Yes' else ['phi'] * num_attributes
    general_h = [['?' for _ in range(num_attributes)] for _ in range(num_attributes)]

    # If the first example was negative, we would need to handle initialization differently,
    # but we assume standard concept learning setup starting with positive or we initialize dynamically.
    if target[0] != 'Yes':
        print("Warning: The first example in the dataset is negative. S initialized to 'phi'.")

    print("Initialization:")
    print(f"S0: {specific_h}")
    print(f"G0: {general_h}\n")

    for i, (instance, label) in enumerate(zip(concepts, target)):
        if label == 'Yes': # Positive instance
            # Generalize S
            for x in range(num_attributes):
                if instance[x] != specific_h[x]:
                    specific_h[x] = '?'

            # Remove from G any hypothesis inconsistent with positive instance
            # (i.e., if general hypothesis does not match the instance, we drop it)
            temp_g = []
            for g in general_h:
                consistent = True
                for x in range(num_attributes):
                    if g[x] != '?' and g[x] != instance[x]:
                        consistent = False
                        break
                if consistent:
                    temp_g.append(g)
            general_h = temp_g

        else: # Negative instance
            # Specialize G to exclude this negative instance
            temp_g = []
            for g in general_h:
                # If the general hypothesis is already inconsistent with this negative instance, keep it
                is_consistent_with_neg = False
                for x in range(num_attributes):
                    if g[x] != '?' and g[x] != instance[x]:
                        is_consistent_with_neg = True
                        break

                if is_consistent_with_neg:
                    temp_g.append(g)
                else:
                    # For each attribute, if it's '?', specialize it
                    for x in range(num_attributes):
                        if g[x] == '?':
                            new_g = g.copy()
                            new_g[x] = specific_h[x] # Use the attribute value from the positive boundary

                            # Ensure it's consistent with the negative instance (it should not match it)
                            if new_g[x] != instance[x] and new_g[x] != '?':
                                # Only keep if it is more general than or equal to S
                                is_more_general = True
                                for k in range(num_attributes):
                                    if new_g[k] != '?' and new_g[k] != specific_h[k]:
                                        is_more_general = False
                                        break
                                if is_more_general and new_g not in temp_g:
                                    temp_g.append(new_g)
            general_h = temp_g

        # Remove redundant/strictly more general hypotheses in G that have more specific ones remaining
        final_g = []
        for g in general_h:
            # Keep only if it's not a generalization of another element in G
            keep = True
            for other in general_h:
                if g != other:
                    # check if other is more specific than g
                    is_other_more_specific = True
                    for x in range(num_attributes):
                        if g[x] != '?' and g[x] != other[x]:
                            is_other_more_specific = False
                            break
                    if is_other_more_specific and any(g[x] == '?' and other[x] != '?' for x in range(num_attributes)):
                        keep = False
                        break
            if keep and g not in final_g:
                final_g.append(g)
        general_h = final_g

        print(f"After Step {i+1} (Instance: {instance}, Label: {label}):")
        print(f"S{i+1}: {specific_h}")
        print(f"G{i+1}: {general_h}\n")

    return specific_h, general_h

# Run the algorithm on the created CSV file
s_final, g_final = candidate_elimination('training_data.csv')

print("Final Version Space Boundary:")
print(f"Specific Boundary (S): {s_final}")
print(f"General Boundary (G): {g_final}")