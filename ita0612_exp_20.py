import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

# 1. Generate Synthetic Sales Data for Demonstration
np.random.seed(42)
dates = pd.date_range(start="2023-01-01", end="2023-12-31", freq="D")
n_days = len(dates)

# Simulating sales with trend, seasonality, and promotional impacts
base_sales = 1000
trend = np.linspace(0, 500, n_days)
seasonality = 300 * np.sin(2 * np.pi * dates.dayofyear / 365)
promo_multiplier = np.random.choice([1.0, 1.5], size=n_days, p=[0.85, 0.15])
noise = np.random.normal(0, 100, n_days)

sales = (base_sales + trend + seasonality) * promo_multiplier + noise

df = pd.DataFrame({
    'Date': dates,
    'Sales': sales,
    'Is_Promo': (promo_multiplier > 1.0).astype(int)
})

# 2. Feature Engineering
df['Year'] = df['Date'].dt.year
df['Month'] = df['Date'].dt.month
df['Day'] = df['Date'].dt.day
df['DayOfWeek'] = df['Date'].dt.dayofweek
df['Is_Weekend'] = df['DayOfWeek'].isin([5, 6]).astype(int)

# Creating lag features (previous days' sales)
for lag in [1, 7, 30]:
    df[f'Sales_Lag_{lag}'] = df['Sales'].shift(lag)

# Drop rows with NaN values resulting from lags
df = df.dropna().reset_index(drop=True)

# 3. Split into Features (X) and Target (y)
features = ['Is_Promo', 'Month', 'Day', 'DayOfWeek', 'Is_Weekend', 'Sales_Lag_1', 'Sales_Lag_7', 'Sales_Lag_30']
X = df[features]
y = df['Sales']

# Time-series safe split (train on earlier data, test on recent data)
split_idx = int(len(df) * 0.8)
X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]

# 4. Model Training
model = RandomForestRegressor(n_estimators=100, random_state=42)
model.fit(X_train, y_train)

# 5. Model Evaluation
y_pred = model.predict(X_test)
mae = mean_absolute_error(y_test, y_pred)
mse = mean_squared_error(y_test, y_pred)
rmse = np.sqrt(mse)
r2 = r2_score(y_test, y_pred)

print("=== Model Performance Evaluation ===")
print(f"Mean Absolute Error (MAE): {mae:.2f}")
print(f"Root Mean Squared Error (RMSE): {rmse:.2f}")
print(f"R-squared (R2) Score: {r2:.2f}")

# 6. Visualization
plt.figure(figsize=(14, 6))
plt.plot(df['Date'].iloc[split_idx:], y_test, label='Actual Sales', color='blue', alpha=0.7)
plt.plot(df['Date'].iloc[split_idx:], y_pred, label='Predicted Sales', color='red', linestyle='--', alpha=0.9)
plt.title('Future Sales Prediction vs Actual Sales')
plt.xlabel('Date')
plt.ylabel('Sales')
plt.legend()
plt.grid(True)
plt.show()